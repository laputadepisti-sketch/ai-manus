function restoreJsonNames(message2) {
  for (const f of message2.field) {
    if (!unsafeIsSetExplicit(f, "jsonName")) {
      f.jsonName = protoCamelCase(f.name);
    }
  }
  message2.nestedType.forEach(restoreJsonNames);
}

