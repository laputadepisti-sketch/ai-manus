function* nestedTypes(desc) {
  switch (desc.kind) {
    case "file":
      for (const message2 of desc.messages) {
        yield message2;
        yield* nestedTypes(message2);
      }
      yield* desc.enums;
      yield* desc.services;
      yield* desc.extensions;
      break;
    case "message":
      for (const message2 of desc.nestedMessages) {
        yield message2;
        yield* nestedTypes(message2);
      }
      yield* desc.nestedEnums;
      yield* desc.nestedExtensions;
      break;
  }
}

